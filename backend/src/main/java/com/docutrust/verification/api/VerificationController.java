package com.docutrust.verification.api;

import java.io.IOException;
import java.util.Optional;

import org.springframework.http.HttpHeaders;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;
import org.springframework.security.core.annotation.AuthenticationPrincipal;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;
import org.springframework.web.multipart.MultipartFile;

import com.docutrust.document.domain.UnsupportedDocumentException;
import com.docutrust.security.domain.AuthenticatedUser;
import com.docutrust.verification.application.VerificationApplicationService;
import com.docutrust.verification.domain.VerificationReport;

import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.tags.Tag;

/**
 * Signature verification.
 *
 * <p>Accepts any PDF, including one DocuTrust never issued. Verification
 * depends only on the file's own contents and the configured trust anchors —
 * it never consults a database to decide whether a signature is valid. That is
 * what makes the result meaningful: the answer would be the same computed by
 * any conformant validator.
 */
@RestController
@RequestMapping("/api/v1/verification")
@Tag(name = "Verification")
public class VerificationController {

    private final VerificationApplicationService verificationService;

    public VerificationController(VerificationApplicationService verificationService) {
        this.verificationService = verificationService;
    }

    @PostMapping(consumes = MediaType.MULTIPART_FORM_DATA_VALUE)
    @Operation(summary = "Verify a submitted PDF's signatures and integrity")
    public VerificationReport verify(@RequestParam("file") MultipartFile file,
                                     @RequestParam(required = false) String documentId,
                                     @AuthenticationPrincipal AuthenticatedUser user) {
        byte[] content;
        try {
            content = file.getBytes();
        } catch (IOException e) {
            throw new UnsupportedDocumentException("The submitted file could not be read.");
        }

        return verificationService.verify(content, file.getOriginalFilename(), documentId, user);
    }

    @GetMapping("/{verificationId}")
    @Operation(summary = "Retrieve a previously recorded verification outcome")
    public ResponseEntity<?> get(@PathVariable String verificationId) {
        return verificationService.findByVerificationId(verificationId)
                .<ResponseEntity<?>>map(record -> ResponseEntity.ok(new StoredVerification(
                        record.getVerificationId(), record.getFileName(),
                        record.getDocumentSha256(), record.getVerdict().name(),
                        record.getSignatureCount(), record.isTamperingDetected(),
                        record.getVerifiedAt().toString())))
                .orElseGet(() -> ResponseEntity.notFound().build());
    }

    public record StoredVerification(String verificationId, String fileName, String documentSha256,
                                     String verdict, int signatureCount,
                                     boolean tamperingDetected, String verifiedAt) {
    }

    /**
     * Downloads a stored verification report.
     *
     * <p>{@code format=html} returns a self-contained document suitable for
     * printing or filing; {@code format=json} returns the machine-readable
     * report. Both describe what verification concluded at that moment — they
     * are a record, not a substitute for verifying again, since trust anchors
     * and revocation state change over time.
     */
    @GetMapping("/{verificationId}/report")
    @Operation(summary = "Download a verification report as HTML or JSON")
    public ResponseEntity<String> report(@PathVariable String verificationId,
                                         @RequestParam(defaultValue = "html") String format) {

        boolean json = "json".equalsIgnoreCase(format);

        Optional<String> body = json
                ? verificationService.reportJson(verificationId)
                : verificationService.reportHtml(verificationId);

        if (body.isEmpty()) {
            return ResponseEntity.notFound().build();
        }

        // The verification ID is generated by the server from SecureRandom and
        // matches a strict pattern, so it is safe to place in a header. It is
        // re-checked here rather than assumed, since this value reaches a
        // Content-Disposition header where a newline would be an injection.
        String safeId = verificationId.replaceAll("[^A-Za-z0-9-]", "");
        String extension = json ? "json" : "html";

        return ResponseEntity.ok()
                .header(HttpHeaders.CONTENT_DISPOSITION,
                        "attachment; filename=\"docutrust-report-" + safeId + "." + extension + "\"")
                .contentType(json ? MediaType.APPLICATION_JSON : MediaType.TEXT_HTML)
                .body(body.get());
    }
}
